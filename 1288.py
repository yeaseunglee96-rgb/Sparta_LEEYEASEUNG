### 혼자 힘으로 풀지 못해 ChatGPT의 도움을 받았고, 계속 복기 중

T = int(input())  # 테스트 케이스 개수

for tc in range(1, T + 1):
    N = int(input())  # 이번 테스트케이스의 시작 숫자 N

    # seen[d] = True  -> 숫자 d(0~9)를 한 번이라도 봤다
    seen = [False] * 10

    cnt = 0  # 지금까지 '서로 다른 숫자(0~9)'를 몇 개 봤는지 카운트
    k = 0    # 몇 번째 배수인지 (1N, 2N, 3N ... 에서 1,2,3을 의미)

    # 0~9를 모두 봤다면 cnt == 10이 되어야 끝난다
    while cnt < 10:
        k += 1              # 다음 배수로 이동
        x = N * k           # 이번에 확인할 숫자 (k*N)

        # x의 각 자리 숫자를 하나씩 확인한다
        # 예: x=2590 -> str(x)="2590" -> '2','5','9','0'
        for ch in str(x):
            d = int(ch)     # 문자 '2' -> 정수 2로 변환

            # 아직 d를 본 적이 없다면 처음 보는 숫자!
            if not seen[d]:
                seen[d] = True  # 이제 봤다고 체크
                cnt += 1        # 서로 다른 숫자를 하나 더 봤으니 +1

    # while이 끝났다는 건 0~9를 다 봤다는 뜻
    # 마지막으로 확인한 수는 k*N
    print(f"#{tc} {N * k}")